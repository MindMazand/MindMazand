#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
G4 - Mazandasht WPF theme dictionaries.

Emits one ResourceDictionary per theme from a single token source so every
theme exposes exactly the same resource keys. Common.xaml (control styles) uses
DynamicResource, so switching the merged theme dictionary re-skins the whole
application without recompiling.

Usage:
    python3 tools/build_themes.py --out app/Mazandasht.Desktop/Assets/Themes
"""
